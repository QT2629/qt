def _lang(lang: str) -> str:
    return "kk" if lang == "kk" else "ru"


def home_keyboard(lang: str) -> Kb:
    btn = TEXTS[_lang(lang)]["btn"]
    return Kb([[Btn(btn[s], callback_data=f"cr:{s}")] for s in SECTIONS])


def back_keyboard(lang: str) -> Kb:
    return Kb([[Btn(TEXTS[_lang(lang)]["btn"]["back"], callback_data="cr:home")]])


def plain_text(lang: str = "ru") -> str:
    """Те же сведения без разметки — в знания для ИИ."""
    parts = [TEXTS[_lang(lang)][k] for k in ("home",) + SECTIONS]
    return re.sub(r"<[^>]+>", "", "\n\n".join(parts))


async def command(update, context: ContextTypes.DEFAULT_TYPE, lang: str) -> None:
    """/creative — список разделов."""
    stats.log_event(update.effective_chat.id, "creative", "home")
    await update.message.reply_text(TEXTS[_lang(lang)]["home"], reply_markup=home_keyboard(lang))


async def on_callback(update, context: ContextTypes.DEFAULT_TYPE, lang: str) -> None:
    """Кнопки «cr:…» под сообщениями про творческие экзамены."""
    query = update.callback_query
    section = query.data.split(":", 1)[1]
    texts = TEXTS[_lang(lang)]
    if section in SECTIONS:
        stats.log_event(update.effective_chat.id, "creative", section)
        text, kb = texts[section] + texts["foot"], back_keyboard(lang)
    else:
        text, kb = texts["home"], home_keyboard(lang)
    try:
        await query.edit_message_text(text, reply_markup=kb)
    except BadRequest as e:
        if "not modified" not in str(e).lower():
            await context.bot.send_message(update.effective_chat.id, text, reply_markup=kb)
