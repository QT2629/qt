def label(cat: str, lang: str = "ru") -> str:
    return LABELS.get(cat, (cat, cat))[lang == "kz"]


def parse(value: str | None) -> list[str]:
    """Квоты из профиля (хранятся строкой «r,large_family»)."""
    return [q for q in (value or "").split(",") if q in SHORT]


def west_of(city: str | None) -> str | None:
    """Гранты для молодёжи западных регионов: Мангистау и Атырау (по городу из профиля)."""
    low = (city or "").lower()
    return next((k for k, words in _WEST.items() if any(w in low for w in words)), None)


def gop_name(gop: str) -> str:
    return (DATA["country"].get(gop) or {}).get("name", "")


def uni(slug: str, gop: str) -> dict:
    """{год: {категория: [грантов, мин. балл]}} по вузу и группе программ."""
    return DATA["unis"].get(slug, {}).get(gop, {})


def country(gop: str) -> dict:
    return {y: v for y, v in (DATA["country"].get(gop) or {}).items() if y in YEARS}


def get(slug: str | None, gop: str, year: str, cat: str) -> list | None:
    """[грантов, мин. балл] — в вузе (slug) или по стране (slug=None)."""
    src = uni(slug, gop) if slug else country(gop)
    v = (src.get(year) or {}).get(cat)
    return v if v and v[0] else None


def cats_for(quotas: list[str], city: str | None = None) -> list[str]:
    """В каких конкурсах человек участвует: общий (или после колледжа), целевые госзаказы и его квоты.
    Квотник всегда участвует и в общем конкурсе."""
    college = "s" in quotas
    out = ["s"] if college else ["g", "ped", "tech", "health"]
    if "r" in quotas and not college:
        out += ["r", "ped_r", "tech_r", "health_r"]
    west = west_of(city)
    if west and not college:
        out.append(west)
    out += [q for q in quotas if q not in ("r", "s")]
    return out


def best(slug: str | None, gop: str, year: str, cats: list[str]) -> tuple[str, int, int | None] | None:
    """Конкурс с самым низким проходным баллом среди доступных человеку: (категория, грантов, мин. балл)."""
    found = [(c, *v) for c in cats if (v := get(slug, gop, year, c))]
    scored = [x for x in found if x[2] is not None]
    if scored:
        return min(scored, key=lambda x: x[2])
    return found[0] if found else None


def word(n: int) -> str:
    return "грант" if n % 10 == 1 and n % 100 != 11 else "гранта" if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14 else "грантов"


def _fmt(v: list, lang: str) -> str:
    n, mn = v
    kz = lang == "kz"
    word_ = "грант" if kz else word(n)
    if mn is None:
        return f"{n} {word_}" + (" (балл ЕНТ тізімде көрсетілмеген)" if kz else " (балл в списке не указан)")
    return f"{n} {word_}, " + (f"{mn} бастап" if kz else f"от {mn}")


def quota_line(slug: str, gop: str, lang: str, limit: int = 6) -> str:
    """Строка для карточки программы: квоты и целевой госзаказ 2026 года в этом вузе по группе."""
    kz = lang == "kz"
    found = [(c, v) for c in (uni(slug, gop).get("2026") or {}) if c not in ("g", "r") and (v := get(slug, gop, "2026", c))]
    if not found:
        return ""
    found.sort(key=lambda cv: -cv[1][0])
    items = [f"{label(c, lang).replace('квота: ', '')} — {_fmt(v, lang)}" for c, v in found[:limit]]
    more = len(found) - limit
    tail = (f"; тағы {more}" if kz else f"; и ещё {more}") if more > 0 else ""
    return ("🎟 2026 жылғы басқа конкурстар (квоталар, мақсатты тапсырыс, колледжден кейін), ЖОО-ға: " if kz
            else "🎟 Другие конкурсы 2026 в этот вуз (квоты, целевой госзаказ, после колледжа): ") \
        + "; ".join(items) + tail


def for_ai(slug: str, gop: str) -> dict | None:
    """Гранты по вузу и группе для ИИ: {год: {«название конкурса»: «N грантов, от X»}} + по стране."""
    def pack(src: dict) -> dict:
        return {y: {label(c): (f"{v[0]} {word(v[0])}, мин. балл {v[1]}" if v[1] is not None else f"{v[0]} {word(v[0])}, балл в списке не указан")
                    for c, v in sorted((src.get(y) or {}).items(), key=lambda kv: -kv[1][0]) if v[0]}
                for y in YEARS if src.get(y)}
    here, nat = pack(uni(slug, gop)), pack(country(gop))
    if not here and not nat:
        return None
    nat = {y: {k: v for k, v in d.items() if "общий" in k or "сельская квота" == k} for y, d in nat.items()}
    return {"group": f"{gop} {gop_name(gop)}", "in_this_university": here, "country_general_and_rural": nat}


def overview() -> str:
    """Сводка для постоянной части базы знаний: по каждой группе — общий конкурс и сельская квота по стране."""
    lines = ["(группа | 2026: общий конкурс — грантов, мин. балл; сельская квота — грантов, мин. балл | 2025: то же)"]
    for gop in sorted(DATA["country"]):
        cells = []
        for y in YEARS:
            g, r = get(None, gop, y, "g"), get(None, gop, y, "r")
            cells.append(f"{y}: общий {g[0]}, от {g[1]}" if g and g[1] is not None else f"{y}: общий —")
            if r and r[1] is not None:
                cells[-1] += f"; сельская {r[0]}, от {r[1]}"
        lines.append(f"{gop} {gop_name(gop)} | " + " | ".join(cells))
    return "\n".join(lines)


